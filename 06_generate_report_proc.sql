CREATE OR REPLACE PROCEDURE GENERATE_REPORT(REPORTID NUMBER)
RETURNS STRING
LANGUAGE SQL
AS
$$

DECLARE

V_QUERY STRING;
V_TARGET STRING;
V_REPORT STRING;

BEGIN

SELECT
QUERY,
TARGET_TABLE,
REPORT_NAME

INTO
:V_QUERY,
:V_TARGET,
:V_REPORT

FROM REPORT_METADATA
WHERE REPORT_ID=:REPORTID;

EXECUTE IMMEDIATE
'CREATE OR REPLACE TABLE '
||V_TARGET||
' AS '
||V_QUERY;

INSERT INTO EXECUTION_LOG
VALUES
(
CURRENT_TIMESTAMP(),
V_REPORT,
'SUCCESS'
);

RETURN 'Report Generated';

END;
$$;