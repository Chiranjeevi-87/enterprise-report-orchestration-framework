CREATE OR REPLACE TABLE EMPLOYEE_DIM
(
EMP_ID NUMBER,
EMP_NAME STRING,
DEPARTMENT STRING,
START_DATE DATE,
END_DATE DATE,
CURRENT_FLAG STRING
);

MERGE INTO EMPLOYEE_DIM T
USING EMPLOYEE_MASTER S

ON T.EMP_ID=S.EMP_ID
AND T.CURRENT_FLAG='Y'

WHEN MATCHED
AND (
T.DEPARTMENT<>S.DEPARTMENT
)

THEN UPDATE SET
END_DATE=CURRENT_DATE()-1,
CURRENT_FLAG='N'

WHEN NOT MATCHED
THEN INSERT
(
EMP_ID,
EMP_NAME,
DEPARTMENT,
START_DATE,
END_DATE,
CURRENT_FLAG
)

VALUES
(
S.EMP_ID,
S.EMP_NAME,
S.DEPARTMENT,
CURRENT_DATE(),
NULL,
'Y'
);